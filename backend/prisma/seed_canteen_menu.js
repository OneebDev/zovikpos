async function seedCanteenMenu() {
  console.log('🌱 Starting canteen menu seed...\n');

  try {
    // Clear existing menu data safely
    console.log('Clearing existing menu items...');
    await prisma.cartItem.deleteMany({});
    await prisma.orderItem.deleteMany({});
    await prisma.menuItem.deleteMany({});
    console.log('✅ Existing items cleared.\n');

    // Seed all items
    console.log(`Seeding ${menuItems.length} menu items...`);
    for (const item of menuItems) {
      await prisma.menuItem.create({ data: { ...item, isActive: true } });
      process.stdout.write('.');
    }

    console.log('\n\n✅ All menu items seeded successfully!');
    console.log(`\n📊 Summary:`);

    const counts = await prisma.menuItem.groupBy({
      by: ['category'],
      _count: { id: true },
    });
    counts.forEach(c => console.log(`  ${c.category}: ${c._count.id} items`));

    const total = await prisma.menuItem.count();
    console.log(`\n  TOTAL: ${total} records in database`);
    console.log('\n🎉 Canteen menu is ready!\n');
  } catch (err) {
    console.error('\n❌ Seed error:', err.message);
  } finally {
    await prisma.$disconnect();
  }
}

seedCanteenMenu();
